def translate(
    language: str,
    key: str,
    /,
    **values: object,
) -> str:
    """Return interface text, falling back to English, then to the key."""
    template = TRANSLATIONS.get(
        language,
        TRANSLATIONS["en"],
    ).get(
        key,
        TRANSLATIONS["en"].get(
            key,
            key,
        ),
    )

    try:
        return template.format(
            **values
        )
    except (
        KeyError,
        ValueError,
    ):
        return template


def choice_key(
    value: object,
) -> str:
    """Return the translation key for a dropdown choice or enum member."""
    enum_name = getattr(value, "name", None)

    if isinstance(enum_name, str):
        return f"{type(value).__name__}.{enum_name}"

    return str(value)
